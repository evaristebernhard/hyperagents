import type { ReactNode } from "react";
export type Navigate = (path: string) => void;
export type ThreadSettings = {
  model: string;
  reasoning: string;
  provider: string;
  mode: string;
  agentId?: string;
  starterAgentName?: string;
  tools: string[];
  outputFormat?: string;
  visuals?: string;
};
export type FileMeta = { id: string; name: string; size: number; mimeType: string; createdAt: string; workspaceId: string };
export type MessageContext = { settings: ThreadSettings; skillIds: string[]; memoryIds: string[]; artifactIds: string[]; integrationIds: string[]; projectId?: string; attachments: FileMeta[] };
export type ToolRun = { id: string; name: string; status: "running" | "success" | "error"; summary: string };
export type DemoMessage = { id?: string; role: "user" | "assistant"; text: string; createdAt?: string; context?: MessageContext; toolRuns?: ToolRun[] };
export type WorkspacePreferences = { defaultThreadSettings?: ThreadSettings; [key: string]: unknown };
export const defaultThreadSettings: ThreadSettings = { model: "", reasoning: "Medium", provider: "Any", mode: "Execute", tools: ["Thread Search", "Documents", "Webpages", "Tables"] };
export type DemoThread = {
  id: string;
  title: string;
  summary: string;
  time: string;
  project?: string;
  starred?: boolean;
  archived?: boolean;
  excluded?: boolean;
  roomId?: string;
  notes?: string;
  messages?: DemoMessage[];
  createdAt?: string;
  updatedAt?: string;
  config?: ThreadSettings;
  projectId?: string;
};
export type DemoProject = {
  id: string;
  name: string;
  description: string;
  goal: string;
  archived?: boolean;
};
export type DemoAgent = {
  id: string;
  name: string;
  description: string;
  prompt: string;
  promptHtml?: string;
  memoryReadScope?: string;
  memorySaveTarget?: string;
  learnsAutomatically?: boolean;
  model?: string;
  provider?: string;
  reasoning?: string;
  tools?: string[];
  skillIds?: string[];
  memoryMode?: string;
  learning?: Record<string, string>;
  libraryEnabled?: boolean;
  archived?: boolean;
  starred?: boolean;
};
export type DemoMemory = {
  id: string;
  content: string;
  category: string;
  importance: number;
  pinned: boolean;
  whenToUse?: string;
  tags?: string[];
  scope?: string;
};
export type PageProps = {
  path: string;
  navigate: Navigate;
  notify: (message: string) => void;
};
export type ResourceProps = PageProps & {
  threads: DemoThread[];
  setThreads: (items: DemoThread[]) => void;
  projects: DemoProject[];
  setProjects: (items: DemoProject[]) => void;
  memories: DemoMemory[];
  setMemories: (items: DemoMemory[]) => void;
  openThread: (id: string) => void;
  onCreateThread: (text: string, project?: string) => void;
};
export type SettingsProps = {
  section: string;
  navigateSection: (section: string) => void;
  onClose: () => void;
  notify: (message: string) => void;
  theme: string;
  setTheme: (theme: string) => void;
};
export type Children = { children: ReactNode };
